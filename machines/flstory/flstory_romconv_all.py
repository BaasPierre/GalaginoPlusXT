def build_maincpu(rs: RomSource) -> bytes:
    """MAME ROM_REGION 0x10000 "maincpu": cpu-a45.15 @0x0000, .16 @0x4000,
    .17 @0x8000 (0xc000 bytes of real ROM). 0xc000-0xffff is never loaded
    (the CPU map's ROM window is only 0x0000-0xbfff) - padded 0xFF."""
    cpu = bytearray(b"\xFF" * 0x10000)
    cpu[0x0000:0x4000] = rs.load("cpu-a45.15")
    cpu[0x4000:0x8000] = rs.load("cpu-a45.16")
    cpu[0x8000:0xC000] = rs.load("cpu-a45.17")
    return bytes(cpu)


def build_audiocpu(rs: RomSource) -> bytes:
    """MAME ROM_REGION 0x10000 "audiocpu": snd.22 @0x0000, snd.23 @0x2000
    (0x4000 bytes of real ROM). sound_map's ROM window is 0x0000-0xbfff plus
    a diagnostic-ROM space at 0xe000-0xefff, neither populated here past
    0x4000 - padded 0xFF."""
    cpu = bytearray(b"\xFF" * 0x10000)
    cpu[0x0000:0x2000] = rs.load("snd.22")
    cpu[0x2000:0x4000] = rs.load("snd.23")
    return bytes(cpu)


def build_bmcu(rs: RomSource) -> bytes:
    """MAME ROM_REGION 0x0800 "bmcu:mcu": a45-20.mcu, verbatim - the whole
    MC68705P5 0x000-0x7ff address space exactly as dumped."""
    return rs.load("a45-20.mcu")


def build_tiles_region(rs: RomSource) -> bytes:
    """MAME ROM_REGION(0x20000, "tiles", ROMREGION_INVERT):
        vid-a45.18 @0x00000  vid-a45.06 @0x04000
        vid-a45.08 @0x08000  vid-a45.20 @0x0c000
        vid-a45.19 @0x10000  vid-a45.07 @0x14000
        vid-a45.09 @0x18000  vid-a45.21 @0x1c000
    ROMREGION_INVERT means MAME XORs every byte of the assembled region with
    0xFF AFTER loading, before gfxdecode (or anything else) reads it - see
    src/emu/romload.cpp's region-post-process step. This step was MISSING
    from the existing tools/romconv/romextract.py-generated flstory_tiles.h
    (verified byte-for-byte against the raw zip: identical, un-inverted) -
    applied here so flstory_tilemap.h / flstory_tiles16.h decode to the
    actual MAME pixel values."""
    region = bytearray()
    for name in ("vid-a45.18", "vid-a45.06", "vid-a45.08", "vid-a45.20",
                 "vid-a45.19", "vid-a45.07", "vid-a45.09", "vid-a45.21"):
        region += rs.load(name)
    assert len(region) == 0x20000, len(region)
    return bytes(b ^ 0xFF for b in region)


def build_chars(region: bytes) -> list[list[list[int]]]:
    """charlayout, GFXDECODE gfx[0] ("tiles", palette base 0, 16 colors):
        8,8  RGN_FRAC(1,2)  4 planes
        planeoffset { RGN_FRAC(1,2)+0, RGN_FRAC(1,2)+4, 0, 4 }
                       ^MSB (2nd half, hi nibble)      ^LSB (1st half, lo nibble)
        xoffs { 3,2,1,0, 8+3,8+2,8+1,8+0 }
        yoffs { 0*16, 1*16, ... 7*16 }
        charincrement 16*8

    region = the full inverted "tiles" ROM_REGION (0x20000), split by
    RGN_FRAC(1,2) into two 0x10000 halves. count = (0x10000*8)/(16*8) = 4096,
    matching get_tile_info's max tile_number = code + ((attr&0xc0)<<2) +
    0x400 + 0x800*char_bank = up to 0xFFF (4096 tiles)."""
    rf = len(region) * 8 // 2                        # RGN_FRAC(1,2) in bits
    planes = [rf + 0, rf + 4, 0, 4]                  # MSB .. LSB
    xoffs = [3, 2, 1, 0, 8 + 3, 8 + 2, 8 + 1, 8 + 0]
    yoffs = [y * 16 for y in range(8)]
    bpt = 16 * 8
    count = rf // bpt
    assert count == 4096, count
    return mame_decode(region, 8, 8, planes, xoffs, yoffs, bpt, count)


def build_sprites16(region: bytes) -> list[list[list[int]]]:
    """spritelayout, GFXDECODE gfx[1] ("tiles", palette base 256, 16 colors):
        16,16  RGN_FRAC(1,2)  4 planes  (same region/planes as charlayout)
        xoffs { 3,2,1,0, 8+3,8+2,8+1,8+0,
                16*8+3,16*8+2,16*8+1,16*8+0, 16*8+8+3,16*8+8+2,16*8+8+1,16*8+8+0 }
        yoffs { 0*16..7*16, 16*16..23*16 }
        charincrement 64*8

    Same 0x20000 inverted region as build_chars(), decoded as 16x16 instead
    of 8x8. count = (0x10000*8)/(64*8) = 1024, matching flstory's 10-bit
    sprite code (spriteram[o+2] + ((spriteram[o+1]&0x30)<<4) = 0..0x3ff)."""
    rf = len(region) * 8 // 2
    planes = [rf + 0, rf + 4, 0, 4]
    xoffs = ([3, 2, 1, 0, 8 + 3, 8 + 2, 8 + 1, 8 + 0] +
             [16 * 8 + 3, 16 * 8 + 2, 16 * 8 + 1, 16 * 8 + 0,
              16 * 8 + 8 + 3, 16 * 8 + 8 + 2, 16 * 8 + 8 + 1, 16 * 8 + 8 + 0])
    yoffs = [y * 16 for y in range(8)] + [y * 16 for y in range(16, 24)]
    bpt = 64 * 8
    count = rf // bpt
    assert count == 1024, count
    return mame_decode(region, 16, 16, planes, xoffs, yoffs, bpt, count)


# --- header writers ------------------------------------------------------
BANNER = "// Generated by flstory_romconv_all.py from the MAME `flstory` (parent) ROM set. Do not edit.\n"


def write_bytes_header(path: Path, guard: str, sym: str, data: bytes,
                        note: str, size_define: str | None = None) -> None:
    with path.open("w") as f:
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        f.write(BANNER)
        f.write(f"// {note}\n\n")
        f.write(f"const unsigned char {sym}[{len(data)}] = {{\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
        f.write("};\n\n")
        if size_define:
            f.write(f"#define {size_define} {len(data)}\n")
        f.write("#endif\n")
    print(f"  wrote {path.name:24s} {len(data):#9x} bytes")


def write_tiles_header(path: Path, guard: str, sym: str, tiles: list, dim: int, note: str) -> None:
    with path.open("w") as f:
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        f.write(BANNER)
        f.write(f"// {note}\n")
        f.write(f"// {len(tiles)} tiles, {dim}x{dim} pixels, ROT0 (natural, unrotated MAME "
                f"orientation - screen rotation for flstory's ROT180 cabinet is entirely "
                f"the renderer's problem (flstory.cpp), not this table's).\n\n")
        f.write(f"const unsigned char {sym}[{len(tiles)}][{dim}][{dim}] = {{\n")
        for i, t in enumerate(tiles):
            rows = ["{" + ",".join(str(v) for v in t[y]) + "}" for y in range(dim)]
            f.write("  {" + ",".join(rows) + "}")
            f.write(",\n" if i < len(tiles) - 1 else "\n")
        f.write("};\n\n#endif\n")
    print(f"  wrote {path.name:24s} {len(tiles)} tiles ({dim}x{dim})")


# --- optional PNG preview ----------------------------------------------
def preview(chars, sprites, outpng: Path) -> None:
    try:
        from PIL import Image
    except ImportError:
        print("  (PIL not installed - skipping preview)")
        return

    PAL = [(20 + i * 14, 20 + i * 10, 220 - i * 12) for i in range(16)]

    def block(ts, dim, cols):
        rows = (len(ts) + cols - 1) // cols
        img = Image.new("RGB", (cols * (dim + 1), rows * (dim + 1)), (32, 32, 96))
        px = img.load()
        for i, t in enumerate(ts):
            ox, oy = (i % cols) * (dim + 1), (i // cols) * (dim + 1)
            for y in range(dim):
                for x in range(dim):
                    px[ox + x, oy + y] = PAL[t[y][x] & 15]
        return img

    # chars: only preview the first 1024 (font/UI range) to keep the image sane
    parts = [block(chars[:1024], 8, 48), block(sprites, 16, 32)]
    W = max(p.width for p in parts)
    H = sum(p.height + 6 for p in parts)
    img = Image.new("RGB", (W, H), (0, 0, 0))
    y = 0
    for p in parts:
        img.paste(p, (0, y))
        y += p.height + 6
    img = img.resize((img.width * 2, img.height * 2), Image.NEAREST)
    img.save(outpng)
    print(f"  wrote {outpng.name} (preview)")


# --------------------------------------------------------------------------
def main() -> None:
    ap = argparse.ArgumentParser(description="Convert the MAME `flstory` (parent) ROM set to flstory headers.")
    ap.add_argument("romsrc", nargs="?", default=None,
                    help="flstory.zip or a folder of loose ROM files "
                         "(default: GalaginoPlus-main/romszip/flstory.zip)")
    ap.add_argument("-o", "--outdir", default=None,
                    help="output folder for the .h files (default: this script's own directory)")
    ap.add_argument("--no-verify", action="store_true", help="skip CRC32 checks")
    ap.add_argument("--no-preview", action="store_true", help="do not write the PNG preview")
    args = ap.parse_args()

    # this script lives in GalaginoPlus-main/source/src/machines/flstory/ ;
    # walk up 4 levels to the repo root (flstory -> machines -> src -> source
    # -> repo root, i.e. GalaginoPlus-main).
    here = Path(__file__).resolve().parent
    root = here.parents[3]
    romsrc = (Path(args.romsrc).resolve() if args.romsrc
              else (root / "romszip" / "flstory.zip").resolve())
    outdir = Path(args.outdir).resolve() if args.outdir else here

    if not romsrc.exists():
        sys.exit(f"ERROR: ROM source {romsrc} does not exist")
    outdir.mkdir(parents=True, exist_ok=True)

    verify = not args.no_verify
    print(f"ROMs : {romsrc}")
    print(f"out  : {outdir}")
    print(f"CRC verify: {'on' if verify else 'OFF'}\n")

    rs = RomSource(romsrc, verify)

